@pytest.mark.parametrize(
    ("sql", "expected"),
    [
        ("SELECT ? + ?", "SELECT %s + %s"),
        ("SELECT '?', 'it''s ?', \"?\", ?", "SELECT '?', 'it''s ?', \"?\", %s"),
        ("SELECT ? -- ?\n, ? /* ? */", "SELECT %s -- ?\n, %s /* ? */"),
        ("SELECT /* a /* ? */ ? */ ?", "SELECT /* a /* ? */ ? */ %s"),
        ("SELECT $$?%$$, $body$?$body$, ?", "SELECT $$?%%$$, $body$?$body$, %s"),
        ("SELECT E'a\\'?%', ?", "SELECT E'a\\'?%%', %s"),
        ("SELECT 'a\\', ?", "SELECT 'a\\', %s"),
        ("SELECT [?], `?`, ?", "SELECT [?], `?`, %s"),
        ("SELECT ? % 5, '10%', '%s' -- %?", "SELECT %s %% 5, '10%%', '%%s' -- %%?"),
    ],
)
def test_qmark_translation_preserves_literals_and_comments(sql: str, expected: str) -> None:
    assert qmark_to_pyformat(sql) == expected


def test_record_preserves_sqlite_row_access_and_dict_conversion() -> None:
    row = Record(("name", "count", "NAME"), ("周恩来", 2, "duplicate"))
    assert row["name"] == row[0] == "周恩来"
    assert row["COUNT"] == row[-2] == 2
    assert row["NAME"] == "周恩来"
    assert row[:] == ("周恩来", 2, "duplicate")
    assert list(row) == ["周恩来", 2, "duplicate"]
    assert dict(row) == {"name": "周恩来", "count": 2, "NAME": "周恩来"}
    with pytest.raises(IndexError):
        row["missing"]


@pytest.mark.parametrize("value", ["元数据\x00标题%", "正常元数据", "", None])
def test_pdf_metadata_encoding_preserves_strings_and_other_bytes(value: str | None) -> None:
    encoded = encode_pdf_metadata(value)
    row = Record(
        ("pdf_title", "pdf_author", "unrelated_blob"),
        (encoded, encoded, b"\x00\xff"),
    )
    assert row["pdf_title"] == row["pdf_author"] == value
    assert row[0] == value
    assert dict(row)["pdf_title"] == value
    assert row["unrelated_blob"] == b"\x00\xff"


def test_postgres_schema_preserves_numeric_precision_and_reference_actions() -> None:
    ddl = postgres_schema(
        "PRAGMA foreign_keys = ON;\n"
        "CREATE TABLE sample ("
        "id INTEGER PRIMARY KEY AUTOINCREMENT, size_bytes INTEGER, score REAL, "
        "parent_id TEXT REFERENCES parent(id) ON DELETE CASCADE, "
        "note TEXT DEFAULT 'REAL INTEGER ? 100%');"
    )
    assert "PRAGMA" not in ddl
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "size_bytes BIGINT" in ddl
    assert "score DOUBLE PRECISION" in ddl
    assert "ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE" in ddl
    assert "'REAL INTEGER ? 100%'" in ddl
    assert POSTGRES_SCHEMA.count("REFERENCES") == POSTGRES_SCHEMA.count(
        "DEFERRABLE INITIALLY IMMEDIATE"
    )
    assert "AUTOINCREMENT" not in POSTGRES_SCHEMA
    assert "pdf_title BYTEA" in POSTGRES_SCHEMA
    assert "pdf_author BYTEA" in POSTGRES_SCHEMA
    assert "pdf_title TEXT" in postgres_schema(
        "CREATE TABLE IF NOT EXISTS unrelated (pdf_title TEXT);"
    )


def test_sqlite_connection_commits_rolls_back_and_closes(work_path: Path) -> None:
    path = work_path / "transactions.db"
    with database_connection(path) as connection:
        connection.execute("CREATE TABLE sample (name TEXT PRIMARY KEY)")
        connection.execute("INSERT INTO sample VALUES (?)", ("committed",))
    with pytest.raises(sqlite3.ProgrammingError):
        connection.execute("SELECT 1")
    with pytest.raises(INTEGRITY_ERRORS), database_connection(path) as connection:
        connection.execute("INSERT INTO sample VALUES (?)", ("rolled back",))
        connection.execute("INSERT INTO sample VALUES (?)", ("committed",))
    with database_connection(path) as connection:
        assert [row[0] for row in connection.execute("SELECT name FROM sample")] == ["committed"]


