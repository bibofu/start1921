@pytest.mark.skipif(
    not os.environ.get("HISTORY_AGENT_TEST_POSTGRES_URL"),
    reason="Set HISTORY_AGENT_TEST_POSTGRES_URL to an isolated PostgreSQL test database",
)
def test_postgres_transactions_precision_and_parameters() -> None:
    """An opt-in driver integration check; temporary tables never alter production data."""

    target = os.environ["HISTORY_AGENT_TEST_POSTGRES_URL"]
    with database_connection(target) as connection:
        connection.execute(
            "CREATE TEMP TABLE backend_probe ("
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "label TEXT UNIQUE, value DOUBLE PRECISION)"
        )
        precise = float.fromhex("0x1.23456789abcdep-2")
        cursor = connection.executemany(
            "INSERT INTO backend_probe (label, value) VALUES (?, ?)",
            [("人物? 100%", precise), ("second", 0.5)],
        )
        assert cursor.rowcount == 2
        row = connection.execute(
            "SELECT id, label, value, '? 10%' AS literal FROM backend_probe WHERE label = ?",
            ("人物? 100%",),
        ).fetchone()
        assert row is not None
        assert row["label"] == "人物? 100%"
        assert row["literal"] == "? 10%"
        assert row["value"].hex() == precise.hex()
        assert row[0] == 1
        assert dict(row)["value"] == precise
        connection.execute("SAVEPOINT before_duplicate")
        with pytest.raises(INTEGRITY_ERRORS):
            connection.execute(
                "INSERT INTO backend_probe (label, value) VALUES (?, ?)", ("second", 1)
            )
        connection.execute("ROLLBACK TO SAVEPOINT before_duplicate")
        assert connection.execute("SELECT COUNT(*) FROM backend_probe").fetchone()[0] == 2


@pytest.fixture
def postgres_target() -> Iterator[str]:
    """Give each real-driver test an isolated schema, including on a shared server."""

    target = os.environ.get("HISTORY_AGENT_TEST_POSTGRES_URL")
    if not target:
        pytest.skip("Set HISTORY_AGENT_TEST_POSTGRES_URL to enable PostgreSQL integration checks")
    schema = f"test_backend_{uuid4().hex}"
    with psycopg.connect(target, autocommit=True) as connection:
        connection.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
    parsed = urlsplit(target)
    query = dict(parse_qsl(parsed.query))
    query["options"] = f"{query.get('options', '')} -csearch_path={schema}".strip()
    scoped_target = urlunsplit(parsed._replace(query=urlencode(query)))
    try:
        yield scoped_target
    finally:
        with psycopg.connect(target, autocommit=True) as connection:
            connection.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(schema)))


def test_postgres_schema_is_idempotent_and_foreign_keys_can_be_deferred(
    postgres_target: str,
) -> None:
    database = Database(postgres_target)
    database.initialize()
    database.initialize()
    assert database.backend == "postgresql"
    assert database.path is None
    with database.connect() as connection:
        versions = connection.execute("SELECT version FROM history_schema_migrations").fetchall()
        assert [row[0] for row in versions] == [POSTGRES_SCHEMA_VERSION]

    person_sql = (
        "INSERT INTO persons (person_id, canonical_name, normalized_name, status, "
        "merged_into_person_id, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?)"
    )
    with pytest.raises(INTEGRITY_ERRORS), database.connect() as connection:
        connection.execute(person_sql, ("source", "s", "s", "merged", "target", "now", "now"))
    with database.connect() as connection:
        assert connection.execute("SELECT COUNT(*) FROM persons").fetchone()[0] == 0
        connection.execute("SET CONSTRAINTS ALL DEFERRED")
        connection.execute(person_sql, ("source", "s", "s", "merged", "target", "now", "now"))
        connection.execute(person_sql, ("target", "t", "t", "active", None, "now", "now"))
    with database.connect() as connection:
        assert connection.execute("SELECT COUNT(*) FROM persons").fetchone()[0] == 2


def test_postgres_pdf_metadata_schema_upgrade_and_nul_roundtrip(postgres_target: str) -> None:
    database = Database(postgres_target)
    database.initialize()
    with database.connect() as connection:
        # Recreate the version-6 column representation with real text data.
        connection.execute(
            "ALTER TABLE document_files ALTER COLUMN pdf_title TYPE TEXT "
            "USING convert_from(pdf_title, 'UTF8'), "
            "ALTER COLUMN pdf_author TYPE TEXT USING convert_from(pdf_author, 'UTF8')"
        )
        connection.execute("DELETE FROM history_schema_migrations")
        connection.execute("INSERT INTO history_schema_migrations (version) VALUES (6)")
        connection.execute(
            "INSERT INTO documents (document_id, title, creators_json, source_type, "
            "source_series_json, verification_status, enabled, ocr_strategy, created_at, "
            "updated_at) VALUES ('fixture', '标题', '[]', 'test', '[]', 'verified', "
            "1, 'none', 'now', 'now')"
        )
        connection.execute(
            "INSERT INTO document_files (document_id, relative_path, filename, sha256, "
            "size_bytes, page_count, modified_at, is_encrypted, first_seen_at, last_seen_at, "
            "pdf_title, pdf_author) VALUES ('fixture', 'fixture.pdf', 'fixture.pdf', 'sha', "
            "1, 1, 'now', 0, 'now', 'now', ?, ?)",
            ("现有正常标题", "正常作者"),
        )
    database.initialize()
    database.initialize()
    with database.connect() as connection:
        row = connection.execute("SELECT pdf_title, pdf_author FROM document_files").fetchone()
        assert tuple(row) == ("现有正常标题", "正常作者")
        assert connection.execute(
            "SELECT MAX(version) FROM history_schema_migrations"
        ).fetchone()[0] == POSTGRES_SCHEMA_VERSION
        metadata = ("中文\x00标题?100%", "\x00作者\x00")
        connection.execute(
            "UPDATE document_files SET pdf_title = ?, pdf_author = ?",
            tuple(encode_pdf_metadata(value) for value in metadata),
        )
    with database.connect() as connection:
        row = connection.execute("SELECT pdf_title, pdf_author FROM document_files").fetchone()
        assert tuple(row) == metadata
        assert dict(row) == {"pdf_title": metadata[0], "pdf_author": metadata[1]}
        raw = connection.execute(
            "SELECT encode(pdf_title, 'hex'), encode(pdf_author, 'hex') FROM document_files"
        ).fetchone()
        assert tuple(raw) == tuple(value.encode("utf-8").hex() for value in metadata)


def test_postgres_conversation_reopen_retention_clear_and_rollback(postgres_target: str) -> None:
    store = ConversationStore(postgres_target)
    store.append_exchange("retained", "保留这个会话?", "内容含100%与'引号'")
    for number in range(102):
        store.append_exchange("trimmed", f"问题{number:03d}", f"回答{number:03d}")

    reopened = ConversationStore(postgres_target)
    messages = reopened.messages("trimmed")
    assert len(messages) == 200
    assert messages[0].content == "问题002"
    assert messages[-1].content == "回答101"
    assert reopened.messages("retained")[1].content == "内容含100%与'引号'"

    with pytest.raises(INTEGRITY_ERRORS), database_connection(postgres_target) as connection:
        connection.execute(
            "INSERT INTO conversation_sessions VALUES (?, ?, ?)", ("rollback", "now", "now")
        )
        connection.executemany(
            "INSERT INTO conversation_messages (session_id, role, content, created_at) "
            "VALUES (?, ?, ?, ?)",
            [("rollback", "user", "first", "now"), ("rollback", "invalid", "second", "now")],
        )
    with database_connection(postgres_target) as connection:
        assert connection.execute(
            "SELECT COUNT(*) FROM conversation_sessions WHERE session_id = ?", ("rollback",)
        ).fetchone()[0] == 0
        assert connection.execute(
            "SELECT COUNT(*) FROM conversation_messages WHERE session_id = ?", ("rollback",)
        ).fetchone()[0] == 0

    reopened.clear("trimmed")
    assert reopened.messages("trimmed") == []
    assert len(reopened.messages("retained")) == 2
