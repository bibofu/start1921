INDEX_VERSION = "postgresql-bm25-jieba-v1"
METADATA_COLUMNS = (
    "chunk_id", "document_id", "title", "filename", "volume", "source_type",
    "verification_status", "creators_json", "pdf_page_start", "pdf_page_end",
    "section_path_json", "text", "year_mentions_json", "scope_status",
    "people_json", "extraction_methods_json",
)
FILTER_INDICES = (1, 5, 13, 10, 12, 14, 7)
# Exhaustively checked against unicode61 remove_diacritics=2 using SQLite
# 3.53.1 fts5vocab(instance): every character in these CJK ranges is retained.
# The public tokenizer also emits Unicode decimal digits via its \d pattern.
# All 680 decimal digits known to this Python build were checked with the same
# oracle. No SQLite tokenizer is consulted at runtime.
UNICODE61_TERMS = re.compile(r"[a-z\d\u3400-\u4dbf\u4e00-\u9fff]+")
ASCII_FOLD = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")
Posting: TypeAlias = tuple[str, int, Sequence[int]]

KEYWORD_SCHEMA = """
CREATE TABLE IF NOT EXISTS keyword_generations (
    generation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    index_version TEXT NOT NULL,
    chunks_count BIGINT NOT NULL DEFAULT 0,
    total_tokens BIGINT NOT NULL DEFAULT 0,
    summary_payload BYTEA,
    manifest_payload BYTEA,
    fingerprint_payload BYTEA
);
CREATE TABLE IF NOT EXISTS keyword_active (
    singleton INTEGER PRIMARY KEY CHECK(singleton = 1),
    generation_id BIGINT NOT NULL REFERENCES keyword_generations(generation_id)
);
CREATE TABLE IF NOT EXISTS keyword_chunks (
    generation_id BIGINT NOT NULL REFERENCES keyword_generations(generation_id),
    rowid BIGINT NOT NULL,
    metadata_rowid BIGINT NOT NULL,
    metadata_payload BYTEA NOT NULL,
    terms_payload BYTEA NOT NULL,
    doc_length BIGINT NOT NULL CHECK(doc_length >= 0),
    filter_payload BYTEA NOT NULL,
    PRIMARY KEY (generation_id, rowid)
);
CREATE TABLE IF NOT EXISTS keyword_postings (
    generation_id BIGINT NOT NULL REFERENCES keyword_generations(generation_id),
    rowid BIGINT NOT NULL,
    term TEXT COLLATE "C" NOT NULL,
    positions INTEGER[] NOT NULL,
    FOREIGN KEY(generation_id, rowid) REFERENCES keyword_chunks(generation_id, rowid)
);
"""

# FTS5 allows 32 KiB terms, larger than PostgreSQL btree keys. unicode61 terms
# cannot contain backslashes, so the immutable text-to-bytea cast has no escape
# ambiguity. Hash collisions fail the unique constraint rather than lose data;
# searches also compare the original term. Keep terms themselves for validation.
KEYWORD_INDEX_UPGRADE = """
ALTER TABLE keyword_postings DROP CONSTRAINT IF EXISTS keyword_postings_pkey;
DROP INDEX IF EXISTS keyword_postings_document;
CREATE UNIQUE INDEX IF NOT EXISTS keyword_postings_identity
    ON keyword_postings(generation_id, sha256(term::bytea), rowid);
CREATE INDEX IF NOT EXISTS keyword_postings_document_order
    ON keyword_postings(generation_id, rowid);
"""


@dataclass(frozen=True)
class IndexedChunk:
    rowid: int
    metadata_rowid: int
    metadata: tuple[Any, ...]
    terms: str
    doc_length: int


def _json_bytes(value: Any) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def _filter_payload(metadata: tuple[Any, ...]) -> bytes:
    return _json_bytes([metadata[index] for index in FILTER_INDICES])


def unicode61_tokens(pretokenized: str) -> list[str]:
    """Tokenize only the alphabet of the existing public tokenizer's output."""

    # FTS5 truncates terms at 32768 UTF-8 bytes, including numeric Unicode runs.
    try:
        return [
            match.group().encode("utf-8")[:32768].decode("utf-8")
            for match in UNICODE61_TERMS.finditer(pretokenized.casefold())
        ]
    except UnicodeDecodeError:
        raise IndexBuildError(
            "A keyword token exceeds the FTS5 byte limit at an invalid UTF-8 boundary"
        ) from None


def positions_for_terms(terms: str) -> dict[str, list[int]]:
    result: dict[str, list[int]] = defaultdict(list)
    for position, term in enumerate(unicode61_tokens(terms)):
        result[term].append(position)
    return dict(result)


class _Fingerprinter:
    def __init__(self) -> None:
        self.chunks_hash = hashlib.sha256()
        self.postings_hash = hashlib.sha256()
        self.chunks_count = 0
        self.postings_count = 0
        self.positions_count = 0
        self.total_tokens = 0
        self.documents: set[str] = set()
        self.terms: set[str] = set()
        self.previous_chunk: int | None = None
        self.previous_posting: tuple[int, str] | None = None

    def add_chunk(self, chunk: IndexedChunk) -> None:
        if len(chunk.metadata) != len(METADATA_COLUMNS):
            raise IndexBuildError("Keyword metadata columns do not match the index schema")
        if self.previous_chunk is not None and chunk.rowid <= self.previous_chunk:
            raise IndexBuildError("Keyword chunks must have unique, increasing FTS rowids")
        if chunk.doc_length < 0:
            raise IndexBuildError("Keyword document length cannot be negative")
        self.previous_chunk = chunk.rowid
        encoded = _json_bytes(
            [chunk.rowid, chunk.metadata_rowid, chunk.metadata, chunk.terms, chunk.doc_length]
        )
        self.chunks_hash.update(len(encoded).to_bytes(8, "big"))
        self.chunks_hash.update(encoded)
        self.chunks_count += 1
        self.total_tokens += chunk.doc_length
        self.documents.add(str(chunk.metadata[1]))

    def add_posting(self, posting: Posting) -> None:
        term, rowid, positions = posting
        key = (rowid, term)
        if self.previous_posting is not None and key <= self.previous_posting:
            raise IndexBuildError("Keyword postings must be unique and ordered by rowid, term")
        if not positions or positions[0] < 0 or any(
            left >= right for left, right in zip(positions, positions[1:], strict=False)
        ):
            raise IndexBuildError("Keyword token positions must be nonempty and increasing")
        self.previous_posting = key
        encoded = _json_bytes([term, rowid, positions])
        self.postings_hash.update(len(encoded).to_bytes(8, "big"))
        self.postings_hash.update(encoded)
        self.postings_count += 1
        self.positions_count += len(positions)
        self.terms.add(term)

    def result(self) -> dict[str, Any]:
        if self.total_tokens != self.positions_count:
            raise IndexBuildError("Keyword document lengths and token occurrence counts differ")
        result = {
            "chunks_sha256": self.chunks_hash.hexdigest(),
            "postings_sha256": self.postings_hash.hexdigest(),
            "chunks_count": self.chunks_count,
            "postings_count": self.postings_count,
            "positions_count": self.positions_count,
            "document_count": len(self.documents),
            "total_tokens": self.total_tokens,
            "term_count": len(self.terms),
        }
        result["sha256"] = hashlib.sha256(_json_bytes(result)).hexdigest()
        return result


def _postgres(connection: Any) -> PostgresConnection:
    if not isinstance(connection, PostgresConnection):
        raise IndexBuildError("Keyword destination must be a PostgreSQL URL")
    return connection


def _ensure_keyword_schema(connection: PostgresConnection) -> None:
    connection.execute("SELECT pg_advisory_xact_lock(1921, 8)")
    existing = connection.execute(
        "SELECT to_regclass('keyword_postings_identity'), "
        "to_regclass('keyword_postings_document_order')"
    ).fetchone()
    if existing is not None and all(value is not None for value in existing):
        # Even ALTER TABLE ... IF EXISTS can hold an exclusive table lock.
        # A normal rebuild must leave the old generation readable during COPY.
        return
    connection.executescript(KEYWORD_SCHEMA)
    connection.executescript(KEYWORD_INDEX_UPGRADE)


def upgrade_keyword_schema(*, target_url: str) -> None:
    """Upgrade indexes transactionally without rewriting published generations."""

    try:
        with database_connection(target_url) as raw:
            _ensure_keyword_schema(_postgres(raw))
    except IndexBuildError:
        raise
    except Exception as exc:
        raise IndexBuildError(
            f"PostgreSQL keyword schema upgrade failed ({type(exc).__name__})"
        ) from None


def _fingerprint_generation(
    connection: PostgresConnection, generation_id: int
) -> dict[str, Any]:
    generation = connection.execute(
        "SELECT index_version FROM keyword_generations WHERE generation_id = ?",
        (generation_id,),
    ).fetchone()
    if generation is None:
        raise IndexBuildError("PostgreSQL keyword generation does not exist")
    if generation[0] != INDEX_VERSION:
        raise IndexBuildError("Unsupported PostgreSQL keyword index version")
    result = _Fingerprinter()
    with connection.raw_connection.cursor(
        name="keyword_verify_chunks", row_factory=tuple_row
    ) as cursor:
        cursor.execute(
            "SELECT rowid, metadata_rowid, metadata_payload, terms_payload, doc_length, "
            "filter_payload FROM keyword_chunks WHERE generation_id = %s ORDER BY rowid",
            (generation_id,),
        )
        for row in cursor:
            metadata = tuple(json.loads(row[2]))
            if bytes(row[5]) != _filter_payload(metadata):
                raise IndexBuildError("Keyword filter metadata differs from original metadata")
            result.add_chunk(IndexedChunk(row[0], row[1], metadata, row[3].decode("utf-8"), row[4]))
    with connection.raw_connection.cursor(
        name="keyword_verify_postings", row_factory=tuple_row
    ) as cursor:
        cursor.execute(
            "SELECT term, rowid, positions FROM keyword_postings "
            "WHERE generation_id = %s ORDER BY rowid, term COLLATE \"C\"",
            (generation_id,),
        )
        for row in cursor:
            result.add_posting((row[0], row[1], row[2]))
    mismatched = connection.execute(
        "SELECT c.rowid FROM keyword_chunks c WHERE c.generation_id = ? AND ("
        "c.doc_length != (SELECT COALESCE(SUM(cardinality(p.positions)), 0) "
        "FROM keyword_postings p WHERE p.generation_id = c.generation_id "
        "AND p.rowid = c.rowid) OR EXISTS ("
        "SELECT 1 FROM keyword_postings p WHERE p.generation_id = c.generation_id "
        "AND p.rowid = c.rowid AND p.positions[cardinality(p.positions)] >= c.doc_length)"
        ") LIMIT 1",
        (generation_id,),
    ).fetchone()
    if mismatched is not None:
        raise IndexBuildError("Keyword document lengths do not match their token positions")
    return result.result()


def _active_generation(connection: PostgresConnection) -> Any:
    row = connection.execute(
        "SELECT g.* FROM keyword_active a JOIN keyword_generations g USING (generation_id) "
        "WHERE a.singleton = 1"
    ).fetchone()
    if row is None:
        raise RetrievalError("PostgreSQL keyword index has no published generation")
    if row["index_version"] != INDEX_VERSION:
        raise RetrievalError("Unsupported PostgreSQL keyword index version")
    return row


def keyword_generation_fingerprint(
    *, target_url: str, generation_id: int | None = None
) -> dict[str, Any]:
    with database_connection(target_url) as raw:
        connection = _postgres(raw)
        connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
        selected = (
            generation_id if generation_id is not None
            else int(_active_generation(connection)["generation_id"])
        )
        return _fingerprint_generation(connection, selected)


def publish_keyword_generation(
    *,
    target_url: str,
    chunks: Iterable[IndexedChunk],
    postings: Iterable[Posting],
    run_id: str,
    started_at: str,
    manifest: dict[str, Any] | None = None,
    expected_fingerprint: dict[str, Any] | None = None,
) -> dict[str, Any]:
    if not is_postgres_target(target_url):
        raise IndexBuildError("Keyword destination must be a PostgreSQL URL")
    try:
        with database_connection(target_url) as raw:
            connection = _postgres(raw)
            _ensure_keyword_schema(connection)
            row = connection.execute(
                "INSERT INTO keyword_generations(index_version) VALUES (?) RETURNING generation_id",
                (INDEX_VERSION,),
            ).fetchone()
            assert row is not None
            generation_id = int(row[0])
            source = _Fingerprinter()
            with connection.raw_connection.cursor().copy(
                "COPY keyword_chunks (generation_id,rowid,metadata_rowid,metadata_payload,"
                "terms_payload,doc_length,filter_payload) FROM STDIN"
            ) as copy:
                for chunk in chunks:
                    source.add_chunk(chunk)
                    copy.write_row(
                        (
                            generation_id, chunk.rowid, chunk.metadata_rowid,
                            _json_bytes(chunk.metadata), chunk.terms.encode("utf-8"),
                            chunk.doc_length, _filter_payload(chunk.metadata),
                        )
                    )
            with connection.raw_connection.cursor().copy(
                "COPY keyword_postings (generation_id,term,rowid,positions) FROM STDIN"
            ) as copy:
                for posting in postings:
                    source.add_posting(posting)
                    term, rowid, positions = posting
                    copy.write_row((generation_id, term, rowid, list(positions)))
            expected = source.result()
            if expected_fingerprint is not None and expected != expected_fingerprint:
                raise IndexBuildError("Keyword source changed after its fingerprint was recorded")
            actual = _fingerprint_generation(connection, generation_id)
            if actual != expected:
                raise IndexBuildError("PostgreSQL keyword full-content verification failed")
            active_manifest = dict(manifest or {})
            active_manifest.update(
                index_artifact_sha256=actual["sha256"],
                keyword_index_version=INDEX_VERSION,
                build_run_id=run_id,
            )
            size_row = connection.execute(
                "SELECT COALESCE(SUM(octet_length(metadata_payload) + "
                "octet_length(terms_payload) + octet_length(filter_payload)), 0) "
                "FROM keyword_chunks WHERE generation_id = ?",
                (generation_id,),
            ).fetchone()
            assert size_row is not None
            size = size_row[0]
            summary = KeywordIndexSummary(
                run_id=run_id, started_at=started_at, finished_at=common.utc_now(),
                index_version=INDEX_VERSION, documents=actual["document_count"],
                chunks=actual["chunks_count"], index_path="postgresql:keyword",
                size_bytes=int(size) + actual["positions_count"] * 4,
                manifest=active_manifest,
            )
            connection.execute(
                "UPDATE keyword_generations SET chunks_count=?, total_tokens=?, "
                "summary_payload=?, manifest_payload=?, fingerprint_payload=? "
                "WHERE generation_id=?",
                (
                    actual["chunks_count"], actual["total_tokens"],
                    _json_bytes(summary.model_dump()), _json_bytes(active_manifest),
                    _json_bytes(actual), generation_id,
                ),
            )
            connection.execute(
                "INSERT INTO keyword_active(singleton, generation_id) VALUES(1, ?) "
                "ON CONFLICT(singleton) DO UPDATE SET generation_id=excluded.generation_id",
                (generation_id,),
            )
        return {
            "generation_id": generation_id, "summary": summary.model_dump(),
            "manifest": active_manifest, "fingerprint": actual,
            "actual_index_artifact_sha256": actual["sha256"], "artifact_verified": True,
        }
    except IndexBuildError:
        raise
    except Exception as exc:
        raise IndexBuildError(
            f"PostgreSQL keyword publication failed ({type(exc).__name__}); "
            "the previous generation remains active"
        ) from None


def load_keyword_index_metadata(target: str) -> dict[str, Any]:
    try:
        with database_connection(target) as raw:
            connection = _postgres(raw)
            connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
            row = _active_generation(connection)
            actual = _fingerprint_generation(connection, int(row["generation_id"]))
            stored = json.loads(row["fingerprint_payload"])
            manifest = json.loads(row["manifest_payload"])
            verified = (
                actual == stored
                and actual["sha256"] == manifest.get("index_artifact_sha256")
                and actual["chunks_count"] == row["chunks_count"]
                and actual["total_tokens"] == row["total_tokens"]
            )
            return {
                "generation_id": int(row["generation_id"]),
                "summary": json.loads(row["summary_payload"]), "manifest": manifest,
                "fingerprint": actual, "actual_index_artifact_sha256": actual["sha256"],
                "artifact_verified": verified,
            }
    except (IndexBuildError, RetrievalError):
        raise
    except Exception as exc:
        raise RetrievalError(
            f"PostgreSQL keyword metadata could not be verified ({type(exc).__name__})"
        ) from None


def _indexed_records(records: Sequence[Any]) -> Iterator[IndexedChunk]:
    for rowid, record in enumerate(records, 1):
        metadata = (
            record.chunk_id, record.document_id, record.title, record.filename, record.volume,
            record.source_type, record.verification_status,
            json.dumps(record.creators, ensure_ascii=False),
            record.pdf_page_start, record.pdf_page_end,
            json.dumps(record.section_path, ensure_ascii=False), record.text,
            json.dumps(record.year_mentions), record.scope_status,
            json.dumps(record.people, ensure_ascii=False), json.dumps(record.extraction_methods),
        )
        terms = " ".join(common.tokenize_for_index(record.search_text))
        yield IndexedChunk(rowid, rowid, metadata, terms, len(unicode61_tokens(terms)))


def build_keyword_index(
    *, chunks_dir: Path, index_path: str, reports_dir: Path, run_id: str,
    project_root: Path | None = None,
) -> KeywordIndexSummary:
    started_at = common.utc_now()
    records = common.load_chunks(chunks_dir)

    def postings() -> Iterator[Posting]:
        for chunk in _indexed_records(records):
            by_term = positions_for_terms(chunk.terms)
            for term in sorted(by_term):
                yield term, chunk.rowid, by_term[term]

    manifest = index_artifact_manifest(
        chunks_dir=chunks_dir, reports_dir=reports_dir,
        project_root=project_root or reports_dir.parents[1],
        run_id=run_id, keyword_index_version=INDEX_VERSION,
    )
    result = publish_keyword_generation(
        target_url=index_path, chunks=_indexed_records(records), postings=postings(),
        run_id=run_id, started_at=started_at, manifest=manifest,
    )
    summary = KeywordIndexSummary.model_validate(result["summary"])
    reports_dir.mkdir(parents=True, exist_ok=True)
    rendered = summary.model_dump_json(indent=2)
    (reports_dir / f"keyword_index_{run_id}.json").write_text(rendered, encoding="utf-8")
    (reports_dir / "keyword_index_latest.json").write_text(rendered, encoding="utf-8")
    return summary


def _phrase_frequencies(
    phrase: list[str], postings: dict[str, dict[int, list[int]]]
) -> dict[int, int]:
    if not phrase:
        return {}
    first = postings.get(phrase[0], {})
    if len(phrase) == 1:
        return {rowid: len(positions) for rowid, positions in first.items()}
    result = {}
    for rowid, positions in first.items():
        starts = set(positions)
        for offset, term in enumerate(phrase[1:], 1):
            starts.intersection_update(
                position - offset for position in postings.get(term, {}).get(rowid, [])
            )
            if not starts:
                break
        if starts:
            result[rowid] = len(starts)
    return result


def search_keyword_index(
    *, index_path: str, query: str, aliases_path: Path, top_k: int = 10,
    document_ids: list[str] | None = None, include_out_of_scope: bool = False,
    section_path_contains: str | None = None, plan: RetrievalPlan | None = None,
) -> SearchResponse:
    terms = common.tokenize_query(query)
    query_intent = plan.query_intent if plan is not None else common.infer_query_intent(query)
    query_years = (
        plan.query_years if plan is not None
        else sorted({int(match.group(1)) for match in common.YEAR.finditer(query)})
    )
    query_year_range = (
        plan.query_year_range if plan is not None else common.infer_year_range(query, query_years)
    )
    explicit_range = bool(plan and plan.query_year_range) or common.has_explicit_year_range(query)
    aliases = load_person_aliases(aliases_path)
    query_people = (
        plan.query_people if plan is not None else sorted(
            person for person, names in aliases.items()
            if person in query or any(alias in query for alias in names)
        )
    )
    filter_people = common.hard_filter_people(query_people, query_intent)
    phrases = [unicode61_tokens(term) for term in terms]
    unique_terms = sorted({term for phrase in phrases for term in phrase})
    response = SearchResponse(
        query=query, query_intent=query_intent, query_terms=terms, query_years=query_years,
        query_year_range=query_year_range, query_people=query_people,
        document_filters=document_ids or [], include_out_of_scope=include_out_of_scope, hits=[],
    )
    try:
        with database_connection(index_path) as raw:
            connection = _postgres(raw)
            connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
            generation = _active_generation(connection)
            generation_id = int(generation["generation_id"])
            n = int(generation["chunks_count"])
            if not n or not unique_terms or top_k == 0:
                return response
            postings: dict[str, dict[int, list[int]]] = defaultdict(dict)
            term_frequencies: dict[str, dict[int, int]] = defaultdict(dict)
            phrase_terms = sorted(
                {term for phrase in phrases if len(phrase) > 1 for term in phrase}
            )
            with connection.raw_connection.cursor(row_factory=tuple_row) as cursor:
                cursor.execute(
                    "SELECT term,rowid,CASE WHEN term = ANY(%s) THEN positions ELSE NULL END,"
                    "cardinality(positions) FROM keyword_postings "
                    "WHERE generation_id = %s AND sha256(term::bytea) = ANY(%s) "
                    "AND term = ANY(%s)",
                    (
                        phrase_terms, generation_id,
                        [hashlib.sha256(term.encode("utf-8")).digest() for term in unique_terms],
                        unique_terms,
                    ),
                )
                for term, rowid, positions, frequency in cursor:
                    term_frequencies[term][rowid] = frequency
                    if positions is not None:
                        postings[term][rowid] = positions
            frequencies = [
                term_frequencies.get(phrase[0], {}) if len(phrase) == 1
                else _phrase_frequencies(phrase, postings)
                for phrase in phrases
            ]
            candidates = sorted({rowid for frequency in frequencies for rowid in frequency})
            if not candidates:
                return response
            idfs = []
            for frequency in frequencies:
                idf = math.log((n - len(frequency) + 0.5) / (len(frequency) + 0.5))
                idfs.append(idf if idf > 0.0 else 1e-6)
            avgdl = int(generation["total_tokens"]) / n
            scored: list[tuple[float, int]] = []
            with connection.raw_connection.cursor(row_factory=tuple_row) as cursor:
                cursor.execute(
                    "SELECT rowid,doc_length,filter_payload FROM keyword_chunks "
                    "WHERE generation_id = %s AND rowid = ANY(%s)",
                    (generation_id, candidates),
                )
                candidate_rows = cursor.fetchall()
            for row in candidate_rows:
                rowid, doc_length = row[0], row[1]
                filters = json.loads(row[2])
                doc, source, scope, sections, years_json, people_json, creators_json = filters
                if document_ids and doc not in document_ids:
                    continue
                if not include_out_of_scope and scope == "out_of_scope":
                    continue
                # LIKE escapes %/_/backslash and folds ASCII case only.
                if section_path_contains and (
                    section_path_contains.translate(ASCII_FOLD)
                    not in sections.translate(ASCII_FOLD)
                ):
                    continue
                if explicit_range or (query_year_range and not query_years):
                    if not any(
                        query_year_range[0] <= year <= query_year_range[1]
                        for year in json.loads(years_json)
                    ):
                        continue
                elif query_years and not any(
                    year in query_years for year in json.loads(years_json)
                ):
                    continue
                if filter_people:
                    people = json.loads(people_json)
                    if any(person not in people for person in filter_people):
                        continue
                score = 0.0
                for idf, frequency in zip(idfs, frequencies, strict=True):
                    tf = float(frequency.get(rowid, 0))
                    score += idf * (
                        (tf * (1.2 + 1.0)) /
                        (tf + 1.2 * (1 - 0.75 + 0.75 * doc_length / avgdl))
                    )
                raw_score = -1.0 * score
                if (query_intent == "timeline" and source == "chronology") or (
                    query_intent == "viewpoint" and source == "selected_works"
                ):
                    raw_score -= 4.0
                if query_people and any(
                    creator in query_people for creator in json.loads(creators_json)
                ):
                    raw_score -= 2.0
                scored.append((raw_score, rowid))
            scored.sort()
            selected = scored if top_k < 0 else scored[:top_k]
            if not selected:
                return response
            with connection.raw_connection.cursor(row_factory=tuple_row) as cursor:
                cursor.execute(
                    "SELECT rowid,metadata_payload FROM keyword_chunks "
                    "WHERE generation_id = %s AND rowid = ANY(%s)",
                    (generation_id, [rowid for _, rowid in selected]),
                )
                full_rows = {
                    row[0]: dict(zip(METADATA_COLUMNS, json.loads(row[1]), strict=True))
                    for row in cursor
                }
            for rank, (raw_score, rowid) in enumerate(selected, 1):
                item = full_rows[rowid]
                response.hits.append(
                    SearchHit(
                        rank=rank, chunk_id=item["chunk_id"], document_id=item["document_id"],
                        title=item["title"], filename=item["filename"], volume=item["volume"],
                        source_type=item["source_type"],
                        verification_status=item["verification_status"],
                        pdf_page_start=item["pdf_page_start"], pdf_page_end=item["pdf_page_end"],
                        section_path=json.loads(item["section_path_json"]), text=item["text"],
                        year_mentions=json.loads(item["year_mentions_json"]),
                        people=json.loads(item["people_json"]),
                        extraction_methods=json.loads(item["extraction_methods_json"]),
                        score=round(-float(raw_score), 6), matched_terms=terms,
                    )
                )
            return response
    except RetrievalError:
        raise
    except DATABASE_ERRORS as exc:
        raise RetrievalError(f"PostgreSQL keyword search failed ({type(exc).__name__})") from None
