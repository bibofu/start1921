"""Small DB-API bridge for the application's SQLite and PostgreSQL stores.

SQLite remains available for migration sources and isolated tests. Business SQL
uses qmark parameters on both backends; values are always bound by the driver.
"""

from __future__ import annotations

import math
import re
import sqlite3
from collections.abc import Callable, Iterable, Iterator, Sequence
from contextlib import contextmanager
from pathlib import Path
from types import TracebackType
from typing import Any, TypeAlias, overload

import psycopg

DATABASE_ERRORS = (sqlite3.Error, psycopg.Error)
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
DatabaseTarget: TypeAlias = Path | str
PDF_METADATA_COLUMNS = frozenset({"pdf_title", "pdf_author"})

_DOLLAR_QUOTE = re.compile(r"\$(?:[A-Za-z_][A-Za-z_0-9]*)?\$")


def _sql_parts(sql: str) -> Iterator[tuple[bool, str]]:
    """Yield executable SQL separately from quoted text and comments."""

    position = 0
    plain_start = 0
    length = len(sql)
    while position < length:
        start = position
        character = sql[position]
        if sql.startswith("--", position):
            end = sql.find("\n", position + 2)
            position = length if end < 0 else end + 1
        elif sql.startswith("/*", position):
            position += 2
            depth = 1
            while position < length and depth:
                if sql.startswith("/*", position):
                    depth += 1
                    position += 2
                elif sql.startswith("*/", position):
                    depth -= 1
                    position += 2
                else:
                    position += 1
        elif character in "'\"`[":
            closing_quote = "]" if character == "[" else character
            # Backslash only escapes inside PostgreSQL E'...' literals. SQLite
            # and ordinary PostgreSQL literals use doubled quote characters.
            escape_literal = (
                character == "'"
                and position > 0
                and sql[position - 1] in "eE"
                and (position < 2 or not (sql[position - 2].isalnum() or sql[position - 2] == "_"))
            )
            position += 1
            while position < length:
                if escape_literal and sql[position] == "\\":
                    position = min(length, position + 2)
                elif sql[position] == closing_quote:
                    position += 1
                    if position < length and sql[position] == closing_quote:
                        position += 1
                    else:
                        break
                else:
                    position += 1
        elif character == "$" and (
            position == 0 or not (sql[position - 1].isalnum() or sql[position - 1] in "_$")
        ):
            match = _DOLLAR_QUOTE.match(sql, position)
            if match is None:
                position += 1
                continue
            delimiter = match.group()
            end = sql.find(delimiter, match.end())
            position = length if end < 0 else end + len(delimiter)
        else:
            position += 1
            continue
        if start > plain_start:
            yield True, sql[plain_start:start]
        yield False, sql[start:position]
        plain_start = position
    if plain_start < length:
        yield True, sql[plain_start:]


def qmark_to_pyformat(sql: str) -> str:
    """Convert bind markers without changing question marks in SQL text.

    psycopg parses percent signs before PostgreSQL parses literals and comments,
    so *all* original percent signs must be doubled when parameters are passed.
    """

    return "".join(
        part.replace("%", "%%").replace("?", "%s") if executable else part.replace("%", "%%")
        for executable, part in _sql_parts(sql)
    )


def postgres_schema(sqlite_schema: str) -> str:
    """Translate this application's versioned DDL, preserving SQLite precision.

    This is deliberately a schema helper, not a general SQLite SQL translator.
    Both stores use inline references, integer flags, text timestamps and JSON
    strings. Foreign keys keep immediate checks unless migration explicitly
    defers them within its transaction.
    """

    def convert(sql: str) -> str:
        sql = re.sub(r"\bPRAGMA\b[^;]*;", "", sql, flags=re.IGNORECASE)
        sql = re.sub(
            r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            sql,
            flags=re.IGNORECASE,
        )
        # SQLite INTEGER and REAL store signed 64-bit integers and binary64.
        sql = re.sub(r"\bINTEGER\b", "BIGINT", sql, flags=re.IGNORECASE)
        sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.IGNORECASE)
        return re.sub(
            r"(\bREFERENCES\s+\w+\s*\(\s*\w+\s*\)"
            r"(?:\s+ON\s+(?:DELETE|UPDATE)\s+"
            r"(?:CASCADE|RESTRICT|NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT))*)",
            r"\1 DEFERRABLE INITIALLY IMMEDIATE",
            sql,
            flags=re.IGNORECASE,
        )

    schema = "".join(
        convert(part) if executable else part for executable, part in _sql_parts(sqlite_schema)
    )
    # Some original PDF metadata contains U+0000, which PostgreSQL TEXT cannot
    # represent. Keep its UTF-8 bytes verbatim in these two opaque metadata
    # fields, while exposing the original strings through Record.
    def metadata_columns(match: re.Match[str]) -> str:
        body = "".join(
            re.sub(r"\b(pdf_title|pdf_author)\s+TEXT\b", r"\1 BYTEA", part)
            if executable
            else part
            for executable, part in _sql_parts(match[2])
        )
        return match[1] + body + match[3]

    return re.sub(
        r"(\bCREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+document_files\s*\()([^;]*)(;)",
        metadata_columns,
        schema,
        flags=re.IGNORECASE,
    )


def encode_pdf_metadata(value: str | None) -> bytes | None:
    """Encode opaque PDF strings without stripping embedded NUL characters."""

    return value.encode("utf-8") if value is not None else None


class Record:
    """A PostgreSQL row with the indexing and iteration of sqlite3.Row."""

    __slots__ = ("_columns", "_indices", "_values")

    def __init__(self, columns: Sequence[str], values: Sequence[Any]) -> None:
        self._columns = tuple(columns)
        self._values = tuple(
            value.decode("utf-8")
            if column in PDF_METADATA_COLUMNS and isinstance(value, bytes)
            else value
            for column, value in zip(columns, values, strict=True)
        )
        self._indices: dict[str, int] = {}
        for index, column in enumerate(columns):
            # sqlite3.Row matches the first column, even when a later duplicate
            # has an exact-case match and the first match differs in ASCII case.
            self._indices.setdefault(column.lower() if column.isascii() else column, index)

    def keys(self) -> list[str]:
        return list(self._columns)

    @overload
    def __getitem__(self, key: int | str) -> Any: ...

    @overload
    def __getitem__(self, key: slice) -> tuple[Any, ...]: ...

    def __getitem__(self, key: int | str | slice) -> Any:
        if isinstance(key, str):
            index = self._indices.get(key.lower() if key.isascii() else key)
            if index is None:
                raise IndexError("No item with that key")
            return self._values[index]
        return self._values[key]

    def __iter__(self) -> Iterator[Any]:
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)


def _record_factory(cursor: psycopg.Cursor[Any]) -> Callable[[Sequence[Any]], Record]:
    columns = tuple(column.name for column in cursor.description or ())
    return lambda values: Record(columns, values)


class PostgresConnection:
    """Expose the subset of sqlite3.Connection used by the project."""

    def __init__(self, connection: psycopg.Connection[Record]) -> None:
        self.raw_connection = connection

    def execute(
        self, sql: str, parameters: Sequence[Any] | None = None
    ) -> psycopg.Cursor[Record]:
        if parameters is None:
            return self.raw_connection.execute(sql)
        return self.raw_connection.execute(qmark_to_pyformat(sql), parameters)

    def executemany(
        self, sql: str, parameters: Iterable[Sequence[Any]]
    ) -> psycopg.Cursor[Record]:
        cursor = self.raw_connection.cursor()
        cursor.executemany(qmark_to_pyformat(sql), parameters)
        return cursor

    def executescript(self, script: str) -> psycopg.Cursor[Record]:
        # No parameters: psycopg's simple-query path supports multiple statements.
        # Unlike SQLite executescript, this does not commit the outer transaction.
        return self.raw_connection.execute(script, prepare=False)

    def commit(self) -> None:
        self.raw_connection.commit()

    def rollback(self) -> None:
        self.raw_connection.rollback()

    def close(self) -> None:
        self.raw_connection.close()

    def __enter__(self) -> PostgresConnection:
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_value: BaseException | None,
        traceback: TracebackType | None,
    ) -> None:
        try:
            if exc_type is None:
                self.commit()
            else:
                self.rollback()
        finally:
            self.close()


Connection: TypeAlias = sqlite3.Connection | PostgresConnection
Row: TypeAlias = sqlite3.Row | Record


def is_postgres_target(target: DatabaseTarget) -> bool:
    return isinstance(target, str) and target.lower().startswith(("postgresql://", "postgres://"))


def connect_database(target: DatabaseTarget, *, timeout: float = 5.0) -> Connection:
    """Open a connection. Callers must close it, or use database_connection."""

    if is_postgres_target(target):
        return PostgresConnection(
            psycopg.connect(
                str(target),
                row_factory=_record_factory,
                connect_timeout=max(1, math.ceil(timeout)),
            )
        )
    path = Path(target)
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path, timeout=timeout)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


@contextmanager
def database_connection(target: DatabaseTarget) -> Iterator[Connection]:
    """Commit successful work, roll back failures, and always close."""

    connection = connect_database(target)
    try:
        yield connection
        connection.commit()
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()
