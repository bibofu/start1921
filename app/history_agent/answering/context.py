class ConversationError(Exception):
    """Base class for session-store failures mapped to HTTP errors."""


class SessionNotFound(ConversationError):
    pass


class SessionBusy(ConversationError):
    pass


class VersionConflict(ConversationError):
    pass


class DuplicateRequest(ConversationError):
    def __init__(self, message_id: int):
        super().__init__("duplicate client_request_id")
        self.message_id = message_id


class SessionLimitExceeded(ConversationError):
    pass


class QuotaExceeded(ConversationError):
    def __init__(self, reset_at: str, retry_after: int, reason: str = "quota"):
        super().__init__(reason)
        self.reset_at = reset_at
        self.retry_after = retry_after
        self.reason = reason


def _session_from_row(row: Any) -> SessionRecord:
    return SessionRecord(
        session_id=str(row["session_id"]),
        visitor_id=str(row["visitor_id"]) if row["visitor_id"] is not None else None,
        title=str(row["title"] or "未命名会话"),
        title_source=str(row["title_source"] or "auto"),
        status=str(row["status"] or "active"),
        pinned=bool(row["pinned"]),
        created_at=str(row["created_at"]),
        updated_at=str(row["updated_at"]),
        last_message_at=str(row["last_message_at"]) if row["last_message_at"] else None,
        message_count=int(row["message_count"] or 0),
        last_message_preview=str(row["last_message_preview"] or ""),
        version=int(row["version"] or 0),
        deleted_at=str(row["deleted_at"]) if row["deleted_at"] else None,
    )


class ConversationStore:
    """PostgreSQL storage for anonymous visitors, sessions, and exchanges."""

    def __init__(self, target: str, *, pepper: str = "start1921-dev-visitor-pepper"):
        if not is_postgres_target(target):
            raise ValueError("A PostgreSQL connection URL is required")
        self.target = target
        self._pepper = pepper
        self._initialized = False
        self._lock = Lock()

    @contextmanager
    def _connect(self) -> Iterator[Connection]:
        self.initialize()
        with database_connection(self.target) as connection:
            yield connection

    def initialize(self) -> None:
        if self._initialized:
            return
        with self._lock:
            if self._initialized:
                return
            with database_connection(self.target) as connection:
                connection.execute("SELECT pg_advisory_xact_lock(1921, 7)")
                connection.executescript(CONVERSATION_SCHEMA)
                connection.executescript(CONVERSATION_ALTERS)
                self._backfill_legacy_sessions(connection)
            self._initialized = True

    def _backfill_legacy_sessions(self, connection: Connection) -> None:
        """Populate display fields for rows created before multi-session support."""

        connection.execute(
            "UPDATE conversation_sessions s SET title = ("
            "SELECT LEFT(m.content, 30) FROM conversation_messages m "
            "WHERE m.session_id = s.session_id AND m.role = 'user' "
            "ORDER BY m.message_id LIMIT 1) "
            "WHERE (s.title IS NULL OR s.title = '') AND EXISTS ("
            "SELECT 1 FROM conversation_messages m WHERE m.session_id = s.session_id)"
        )
        connection.execute(
            "UPDATE conversation_sessions s SET title = COALESCE(NULLIF(s.title, ''), '历史会话'), "
            "title_source = COALESCE(NULLIF(s.title_source, ''), 'auto') "
            "WHERE s.title IS NULL OR s.title = ''"
        )
        connection.execute(
            "UPDATE conversation_sessions s SET last_message_at = ("
            "SELECT MAX(m.created_at) FROM conversation_messages m "
            "WHERE m.session_id = s.session_id) "
            "WHERE s.last_message_at IS NULL"
        )
        connection.execute(
            "UPDATE conversation_sessions s SET message_count = ("
            "SELECT COUNT(*) FROM conversation_messages m WHERE m.session_id = s.session_id) "
            "WHERE s.message_count = 0 AND EXISTS ("
            "SELECT 1 FROM conversation_messages m WHERE m.session_id = s.session_id)"
        )
        connection.execute(
            "UPDATE conversation_sessions s SET last_message_preview = COALESCE(("
            "SELECT LEFT(m.content, 160) FROM conversation_messages m "
            "WHERE m.session_id = s.session_id AND m.role = 'assistant' "
            "ORDER BY m.message_id DESC LIMIT 1), '') "
            "WHERE s.last_message_preview IS NULL OR s.last_message_preview = ''"
        )
        connection.execute(
            "UPDATE conversation_sessions s SET search_text = COALESCE(("
            "SELECT LEFT(STRING_AGG(m.content, ' ' ORDER BY m.message_id), 4000) "
            "FROM conversation_messages m WHERE m.session_id = s.session_id "
            "AND m.role = 'user'), '') "
            "WHERE s.search_text IS NULL OR s.search_text = ''"
        )

    # ------------------------------------------------------------------
    # Visitors and tokens
    # ------------------------------------------------------------------

    def create_visitor(
        self, *, ip_hash: str = "", user_agent_hash: str = ""
    ) -> tuple[VisitorContext, str]:
        visitor_id = uuid4().hex
        token = secrets.token_urlsafe(32)
        csrf_secret = secrets.token_urlsafe(24)
        now = _now()
        expires_at = (datetime.now(UTC) + timedelta(days=365)).isoformat()
        with self._connect() as connection:
            connection.execute(
                "INSERT INTO visitors(visitor_id, status, created_at, last_seen_at, "
                "first_ip_hash, first_user_agent_hash) VALUES (?, 'active', ?, ?, ?, ?)",
                (visitor_id, now, now, ip_hash, user_agent_hash),
            )
            connection.execute(
                "INSERT INTO visitor_tokens(token_id, visitor_id, token_hash, csrf_secret, "
                "created_at, last_used_at, expires_at) VALUES (?, ?, ?, ?, ?, ?, ?)",
                (
                    uuid4().hex,
                    visitor_id,
                    _hash_token(token, self._pepper),
                    csrf_secret,
                    now,
                    now,
                    expires_at,
                ),
            )
            day = date.today()
            connection.execute(
                "INSERT INTO usage_ip_daily(ip_hash, day, visitors_created) VALUES (?, ?, 1) "
                "ON CONFLICT(ip_hash, day) DO UPDATE SET "
                "visitors_created = usage_ip_daily.visitors_created + 1",
                (ip_hash or "unknown", day),
            )
        context = VisitorContext(
            visitor_id=visitor_id,
            label=f"v_{visitor_id[:8]}",
            csrf_secret=csrf_secret,
        )
        return context, token

    def resolve_visitor(self, token: str) -> VisitorContext | None:
        if not token:
            return None
        token_hash = _hash_token(token, self._pepper)
        with self._connect() as connection:
            row = connection.execute(
                "SELECT v.visitor_id, v.status, t.csrf_secret, t.expires_at, t.revoked_at "
                "FROM visitor_tokens t JOIN visitors v ON v.visitor_id = t.visitor_id "
                "WHERE t.token_hash = ?",
                (token_hash,),
            ).fetchone()
        if row is None or row["status"] != "active" or row["revoked_at"] is not None:
            return None
        if str(row["expires_at"]) < _now():
            return None
        return VisitorContext(
            visitor_id=str(row["visitor_id"]),
            label=f"v_{str(row['visitor_id'])[:8]}",
            csrf_secret=str(row["csrf_secret"]),
        )

    def touch_visitor(self, visitor_id: str) -> None:
        with self._connect() as connection:
            connection.execute(
                "UPDATE visitors SET last_seen_at = ? WHERE visitor_id = ?",
                (_now(), visitor_id),
            )

    def get_visitor_label(self, visitor_id: str) -> str:
        return f"v_{visitor_id[:8]}"

    # ------------------------------------------------------------------
    # Sessions
    # ------------------------------------------------------------------

    def count_sessions(self, visitor_id: str) -> int:
        with self._connect() as connection:
            row = connection.execute(
                "SELECT COUNT(*) FROM conversation_sessions "
                "WHERE visitor_id = ? AND status <> 'deleted'",
                (visitor_id,),
            ).fetchone()
        return int(row[0]) if row is not None else 0

    def create_session(self, visitor_id: str, *, title: str | None = None) -> SessionRecord:
        session_id = uuid4().hex
        now = _now()
        title_value = _clean_text(title, MAX_TITLE_CHARS) if title else None
        with self._connect() as connection:
            connection.execute(
                "INSERT INTO conversation_sessions(session_id, visitor_id, title, "
                "title_source, status, created_at, updated_at, last_message_at) "
                "VALUES (?, ?, ?, ?, 'active', ?, ?, ?)",
                (
                    session_id,
                    visitor_id,
                    title_value,
                    "user" if title_value else "auto",
                    now,
                    now,
                    now,
                ),
            )
        return self.get_session(visitor_id, session_id)

    def get_session(
        self, visitor_id: str, session_id: str, *, include_deleted: bool = False
    ) -> SessionRecord:
        with self._connect() as connection:
            row = connection.execute(
                "SELECT * FROM conversation_sessions WHERE session_id = ? AND visitor_id = ?",
                (session_id, visitor_id),
            ).fetchone()
        if row is None or (row["status"] == "deleted" and not include_deleted):
            raise SessionNotFound(session_id)
        return _session_from_row(row)

    def list_sessions(
        self,
        visitor_id: str,
        *,
        limit: int = 50,
        offset: int = 0,
        query: str = "",
        status: str = "active",
    ) -> tuple[list[SessionRecord], bool]:
        limit = max(1, min(limit, 100))
        offset = max(0, offset)
        where = ["visitor_id = ?", "status = ?"]
        parameters: list[Any] = [visitor_id, status]
        if query:
            escaped = query.replace("%", "\\%").replace("_", "\\_")
            like = f"%{escaped}%"
            where.append(
                "(COALESCE(title, '') ILIKE ? ESCAPE '\\' OR "
                "COALESCE(last_message_preview, '') ILIKE ? ESCAPE '\\' OR "
                "COALESCE(search_text, '') ILIKE ? ESCAPE '\\')"
            )
            parameters.extend([like, like, like])
        sql = (
            "SELECT * FROM conversation_sessions WHERE "
            + " AND ".join(where)
            + " ORDER BY pinned DESC, COALESCE(last_message_at, updated_at, created_at) DESC, "
            "session_id DESC LIMIT ? OFFSET ?"
        )
        parameters.extend([limit + 1, offset])
        with self._connect() as connection:
            rows = connection.execute(sql, tuple(parameters)).fetchall()
        return [_session_from_row(row) for row in rows[:limit]], len(rows) > limit

    def rename_session(
        self, visitor_id: str, session_id: str, title: str, *, expected_version: int | None = None
    ) -> SessionRecord:
        title_value = _clean_text(title, MAX_TITLE_CHARS)
        if not title_value:
            raise ValueError("title cannot be empty")
        now = _now()
        with self._connect() as connection:
            parameters: list[Any] = [title_value, now, session_id, visitor_id]
            version_clause = ""
            if expected_version is not None:
                version_clause = " AND version = ?"
                parameters.append(expected_version)
            row = connection.execute(
                "UPDATE conversation_sessions SET title = ?, title_source = 'user', "
                "updated_at = ?, version = version + 1 WHERE session_id = ? AND visitor_id = ?"
                + version_clause
                + " RETURNING *",
                tuple(parameters),
            ).fetchone()
            if row is None:
                self._raise_update_error(connection, visitor_id, session_id, expected_version)
        return _session_from_row(row)

    def set_pinned(self, visitor_id: str, session_id: str, pinned: bool) -> SessionRecord:
        now = _now()
        with self._connect() as connection:
            row = connection.execute(
                "UPDATE conversation_sessions SET pinned = ?, updated_at = ?, "
                "version = version + 1 WHERE session_id = ? AND visitor_id = ? RETURNING *",
                (pinned, now, session_id, visitor_id),
            ).fetchone()
            if row is None:
                self._raise_update_error(connection, visitor_id, session_id, None)
        return _session_from_row(row)

    def set_archived(self, visitor_id: str, session_id: str, archived: bool) -> SessionRecord:
        now = _now()
        with self._connect() as connection:
            row = connection.execute(
                "UPDATE conversation_sessions SET status = ?, updated_at = ?, "
                "version = version + 1 WHERE session_id = ? AND visitor_id = ? "
                "AND status <> 'deleted' RETURNING *",
                ("archived" if archived else "active", now, session_id, visitor_id),
            ).fetchone()
            if row is None:
                self._raise_update_error(connection, visitor_id, session_id, None)
        return _session_from_row(row)

    def soft_delete(self, visitor_id: str, session_id: str) -> SessionRecord:
        now = _now()
        with self._connect() as connection:
            row = connection.execute(
                "UPDATE conversation_sessions SET status = 'deleted', deleted_at = ?, "
                "active_run_id = NULL, active_run_started_at = NULL, updated_at = ?, "
                "version = version + 1 WHERE session_id = ? AND visitor_id = ? "
                "AND status <> 'deleted' RETURNING *",
                (now, now, session_id, visitor_id),
            ).fetchone()
            if row is None:
                self._raise_update_error(connection, visitor_id, session_id, None)
            connection.execute(
                "UPDATE conversation_messages SET status = 'aborted' "
                "WHERE session_id = ? AND status IN ('pending', 'running')",
                (session_id,),
            )
        return _session_from_row(row)

    def restore_session(self, visitor_id: str, session_id: str) -> SessionRecord:
        now = _now()
        with self._connect() as connection:
            row = connection.execute(
                "UPDATE conversation_sessions SET status = 'active', deleted_at = NULL, "
                "updated_at = ?, version = version + 1 WHERE session_id = ? AND visitor_id = ? "
                "AND status = 'deleted' RETURNING *",
                (now, session_id, visitor_id),
            ).fetchone()
            if row is None:
                self._raise_update_error(connection, visitor_id, session_id, None)
        return _session_from_row(row)

    def claim_session(self, visitor_id: str, legacy_session_id: str) -> SessionRecord:
        now = _now()
        cutoff = (datetime.now(UTC) - timedelta(days=30)).isoformat()
        with self._connect() as connection:
            row = connection.execute(
                "UPDATE conversation_sessions SET visitor_id = ?, updated_at = ? "
                "WHERE session_id = ? AND visitor_id IS NULL AND status <> 'deleted' "
                "AND COALESCE(updated_at, created_at) >= ? RETURNING *",
                (visitor_id, now, legacy_session_id, cutoff),
            ).fetchone()
            if row is None:
                raise SessionNotFound(legacy_session_id)
        return _session_from_row(row)

    def _raise_update_error(
        self,
        connection: Connection,
        visitor_id: str,
        session_id: str,
        expected_version: int | None,
    ) -> None:
        row = connection.execute(
            "SELECT version FROM conversation_sessions WHERE session_id = ? AND visitor_id = ?",
            (session_id, visitor_id),
        ).fetchone()
        if row is None:
            raise SessionNotFound(session_id)
        if expected_version is not None:
            raise VersionConflict(session_id)
        raise SessionNotFound(session_id)

