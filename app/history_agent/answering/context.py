    def usage_snapshot(self, visitor_id: str) -> dict[str, int]:
        with self._connect() as connection:
            row = connection.execute(
                "SELECT questions, prompt_tokens, completion_tokens, reserved_tokens "
                "FROM usage_daily WHERE visitor_id = ? AND day = ?",
                (visitor_id, date.today()),
            ).fetchone()
        if row is None:
            return {"questions": 0, "tokens": 0}
        return {
            "questions": int(row["questions"] or 0),
            "tokens": int(row["prompt_tokens"] or 0)
            + int(row["completion_tokens"] or 0)
            + int(row["reserved_tokens"] or 0),
        }

    def reserve_quota(
        self,
        visitor_id: str,
        ip_hash: str,
        estimated_tokens: int,
        limits: QuotaLimits,
    ) -> QuotaReservation | None:
        if not limits.enabled:
            return None
        day = date.today()
        estimated = max(1, int(estimated_tokens))
        reset_at, retry_after = _next_quota_reset()
        with self._connect() as connection:
            connection.execute(
                "INSERT INTO usage_daily(visitor_id, day) VALUES (?, ?) "
                "ON CONFLICT(visitor_id, day) DO NOTHING",
                (visitor_id, day),
            )
            connection.execute(
                "INSERT INTO usage_ip_daily(ip_hash, day) VALUES (?, ?) "
                "ON CONFLICT(ip_hash, day) DO NOTHING",
                (ip_hash or "unknown", day),
            )
            connection.execute(
                "INSERT INTO global_usage_daily(day) VALUES (?) ON CONFLICT(day) DO NOTHING",
                (day,),
            )
            visitor_row = connection.execute(
                "SELECT * FROM usage_daily WHERE visitor_id = ? AND day = ? FOR UPDATE",
                (visitor_id, day),
            ).fetchone()
            ip_row = connection.execute(
                "SELECT * FROM usage_ip_daily WHERE ip_hash = ? AND day = ? FOR UPDATE",
                (ip_hash or "unknown", day),
            ).fetchone()
            global_row = connection.execute(
                "SELECT * FROM global_usage_daily WHERE day = ? FOR UPDATE", (day,)
            ).fetchone()
            if (
                visitor_row is None
                or ip_row is None
                or global_row is None
                or int(visitor_row["questions"]) + 1 > limits.visitor_daily_questions
                or int(ip_row["questions"]) + 1 > limits.ip_daily_questions
                or int(visitor_row["prompt_tokens"])
                + int(visitor_row["completion_tokens"])
                + int(visitor_row["reserved_tokens"])
                + estimated
                > limits.visitor_daily_tokens
                or int(ip_row["tokens"]) + estimated > limits.ip_daily_tokens
                or int(global_row["tokens"])
                + int(global_row["reserved_tokens"])
                + estimated
                > limits.global_daily_tokens
            ):
                raise QuotaExceeded(reset_at, retry_after)
            connection.execute(
                "UPDATE usage_daily SET questions = questions + 1, "
                "reserved_tokens = reserved_tokens + ? WHERE visitor_id = ? AND day = ?",
                (estimated, visitor_id, day),
            )
            connection.execute(
                "UPDATE usage_ip_daily SET questions = questions + 1 WHERE ip_hash = ? AND day = ?",
                (ip_hash or "unknown", day),
            )
            connection.execute(
                "UPDATE global_usage_daily SET questions = questions + 1, "
                "reserved_tokens = reserved_tokens + ? WHERE day = ?",
                (estimated, day),
            )
        return QuotaReservation(
            visitor_id=visitor_id,
            ip_hash=ip_hash or "unknown",
            day=day,
            reserved_tokens=estimated,
        )

    def settle_quota(
        self,
        reservation: QuotaReservation | None,
        *,
        prompt_tokens: int = 0,
        completion_tokens: int = 0,
    ) -> None:
        if reservation is None:
            return
        total = max(0, int(prompt_tokens)) + max(0, int(completion_tokens))
        with self._connect() as connection:
            connection.execute(
                "UPDATE usage_daily SET reserved_tokens = GREATEST(0, reserved_tokens - ?), "
                "prompt_tokens = prompt_tokens + ?, completion_tokens = completion_tokens + ? "
                "WHERE visitor_id = ? AND day = ?",
                (
                    reservation.reserved_tokens,
                    max(0, int(prompt_tokens)),
                    max(0, int(completion_tokens)),
                    reservation.visitor_id,
                    reservation.day,
                ),
            )
            connection.execute(
                "UPDATE usage_ip_daily SET tokens = tokens + ? WHERE ip_hash = ? AND day = ?",
                (total, reservation.ip_hash, reservation.day),
            )
            connection.execute(
                "UPDATE global_usage_daily SET reserved_tokens = GREATEST(0, reserved_tokens - ?), "
                "tokens = tokens + ? WHERE day = ?",
                (reservation.reserved_tokens, total, reservation.day),
            )

    def release_quota(self, reservation: QuotaReservation | None) -> None:
        if reservation is None:
            return
        with self._connect() as connection:
            connection.execute(
                "UPDATE usage_daily SET reserved_tokens = GREATEST(0, reserved_tokens - ?) "
                "WHERE visitor_id = ? AND day = ?",
                (reservation.reserved_tokens, reservation.visitor_id, reservation.day),
            )
            connection.execute(
                "UPDATE global_usage_daily SET reserved_tokens = GREATEST(0, reserved_tokens - ?) "
                "WHERE day = ?",
                (reservation.reserved_tokens, reservation.day),
            )
