    def session_messages(
        self,
        visitor_id: str,
        session_id: str,
        *,
        before: int | None = None,
        limit: int = 50,
        include_unfinished: bool = True,
    ) -> list[ConversationMessage]:
        limit = max(1, min(limit, 200))
        with self._connect() as connection:
            session = connection.execute(
                "SELECT 1 FROM conversation_sessions WHERE session_id = ? AND visitor_id = ? "
                "AND status <> 'deleted'",
                (session_id, visitor_id),
            ).fetchone()
            if session is None:
                raise SessionNotFound(session_id)
            where = ["session_id = ?"]
            parameters: list[Any] = [session_id]
            if before is not None:
                where.append("message_id < ?")
                parameters.append(before)
            if not include_unfinished:
                where.append("status NOT IN ('aborted', 'failed')")
            parameters.append(limit)
            rows = connection.execute(
                "SELECT message_id, role, content, status, created_at FROM conversation_messages "
                "WHERE " + " AND ".join(where) + " ORDER BY message_id DESC LIMIT ?",
                tuple(parameters),
            ).fetchall()
        messages = [
            ConversationMessage(
                message_id=int(row["message_id"]),
                role=row["role"],
                content=str(row["content"]),
                status=row["status"],
                created_at=str(row["created_at"]),
            )
            for row in rows
        ]
        messages.reverse()
        return messages

    def messages(self, session_id: str, *, limit: int = 200) -> list[ConversationMessage]:
        """Legacy reader used by migration tests and non-visitor tooling."""

        with self._connect() as connection:
            rows = connection.execute(
                "SELECT message_id, role, content, status, created_at FROM conversation_messages "
                "WHERE session_id = ? ORDER BY message_id DESC LIMIT ?",
                (session_id, limit),
            ).fetchall()
        messages = [
            ConversationMessage(
                message_id=int(row["message_id"]),
                role=row["role"],
                content=str(row["content"]),
                status=row["status"],
                created_at=str(row["created_at"]),
            )
            for row in rows
        ]
        messages.reverse()
        return messages

    def begin_question(
        self,
        visitor_id: str,
        session_id: str,
        question: str,
        client_request_id: str | None = None,
    ) -> QuestionStart:
        request_id = client_request_id or uuid4().hex
        run_id = uuid4().hex
        now = _now()
        with self._connect() as connection:
            session = connection.execute(
                "SELECT * FROM conversation_sessions WHERE session_id = ? AND visitor_id = ? "
                "FOR UPDATE",
                (session_id, visitor_id),
            ).fetchone()
            if session is None or session["status"] != "active":
                raise SessionNotFound(session_id)
            active_started = _parse_time(session["active_run_started_at"])
            if (
                session["active_run_id"]
                and active_started is not None
                and datetime.now(UTC) - active_started < RUN_LEASE
            ):
                raise SessionBusy(session_id)
            duplicate = connection.execute(
                "SELECT message_id FROM conversation_messages WHERE session_id = ? "
                "AND client_request_id = ? AND role = 'user'",
                (session_id, request_id),
            ).fetchone()
            if duplicate is not None:
                raise DuplicateRequest(int(duplicate["message_id"]))
            inserted = connection.execute(
                "INSERT INTO conversation_messages(session_id, role, content, status, "
                "client_request_id, created_at) VALUES (?, 'user', ?, 'pending', ?, ?) "
                "RETURNING message_id",
                (session_id, question, request_id, now),
            ).fetchone()
            if inserted is None:
                raise SessionNotFound(session_id)
            title = session["title"]
            connection.execute(
                "UPDATE conversation_sessions SET title = ?, title_source = ?, "
                "last_message_at = ?, updated_at = ?, message_count = message_count + 1, "
                "last_message_preview = ?, "
                "search_text = LEFT(COALESCE(search_text, '') || ? || ' ', ?), "
                "active_run_id = ?, active_run_started_at = ?, version = version + 1 "
                "WHERE session_id = ?",
                (
                    title or _title_from_question(question),
                    session["title_source"] if title else "auto",
                    now,
                    now,
                    _preview(question),
                    question,
                    MAX_SEARCH_CHARS,
                    run_id,
                    now,
                    session_id,
                ),
            )
        return QuestionStart(message_id=int(inserted["message_id"]), run_id=run_id)

    def complete_question(
        self,
        visitor_id: str,
        session_id: str,
        user_message_id: int,
        answer: str,
        run_id: str,
        *,
        client_request_id: str | None = None,
    ) -> bool:
        now = _now()
        with self._connect() as connection:
            session = connection.execute(
                "SELECT * FROM conversation_sessions WHERE session_id = ? AND visitor_id = ? "
                "FOR UPDATE",
                (session_id, visitor_id),
            ).fetchone()
            if (
                session is None
                or session["status"] == "deleted"
                or session["active_run_id"] != run_id
            ):
                return False
            connection.execute(
                "UPDATE conversation_messages SET status = 'completed' "
                "WHERE message_id = ? AND session_id = ? AND status IN ('pending', 'running')",
                (user_message_id, session_id),
            )
            connection.execute(
                "INSERT INTO conversation_messages(session_id, role, content, status, "
                "client_request_id, created_at) VALUES (?, 'assistant', ?, 'completed', ?, ?) "
                "ON CONFLICT DO NOTHING",
                (session_id, answer[:MAX_MESSAGE_CHARS], client_request_id, now),
            )
            connection.execute(
                "UPDATE conversation_sessions SET message_count = message_count + 1, "
                "last_message_at = ?, updated_at = ?, last_message_preview = ?, "
                "active_run_id = NULL, active_run_started_at = NULL, version = version + 1 "
                "WHERE session_id = ?",
                (now, now, _preview(answer), session_id),
            )
        return True

    def abort_question(
        self,
        visitor_id: str,
        session_id: str,
        user_message_id: int,
        run_id: str,
        *,
        failed: bool = False,
    ) -> None:
        now = _now()
        with self._connect() as connection:
            session = connection.execute(
                "SELECT active_run_id FROM conversation_sessions "
                "WHERE session_id = ? AND visitor_id = ?",
                (session_id, visitor_id),
            ).fetchone()
            if session is None or session["active_run_id"] != run_id:
                return
            connection.execute(
                "UPDATE conversation_messages SET status = ? "
                "WHERE message_id = ? AND session_id = ?",
                ("failed" if failed else "aborted", user_message_id, session_id),
            )
            connection.execute(
                "UPDATE conversation_sessions SET active_run_id = NULL, "
                "active_run_started_at = NULL, updated_at = ? WHERE session_id = ?",
                (now, session_id),
            )

    def append_exchange(self, session_id: str, question: str, answer: str) -> None:
        """Compatibility writer for migration tests and legacy tooling."""

        timestamp = _now()
        with self._connect() as connection:
            connection.execute(
                "INSERT INTO conversation_sessions(session_id, created_at, updated_at, "
                "last_message_at) VALUES (?, ?, ?, ?) ON CONFLICT(session_id) DO UPDATE SET "
                "updated_at = excluded.updated_at, last_message_at = excluded.last_message_at",
                (session_id, timestamp, timestamp, timestamp),
            )
            connection.executemany(
                "INSERT INTO conversation_messages(session_id, role, content, status, created_at) "
                "VALUES (?, ?, ?, 'completed', ?)",
                (
                    (session_id, "user", question, timestamp),
                    (session_id, "assistant", answer, timestamp),
                ),
            )
            connection.execute(
                "UPDATE conversation_sessions SET title = COALESCE(NULLIF(title, ''), ?), "
                "message_count = message_count + 2, last_message_at = ?, updated_at = ?, "
                "last_message_preview = ?, "
                "search_text = LEFT(COALESCE(search_text, '') || ? || ' ', ?), "
                "version = version + 1 WHERE session_id = ?",
                (
                    _title_from_question(question),
                    timestamp,
                    timestamp,
                    _preview(answer),
                    question,
                    MAX_SEARCH_CHARS,
                    session_id,
                ),
            )

